"""
Утилиты для работы со слагами (транслитерация)
"""
import re


def transliterate_to_slug(text):
    """
    Транслитерирует русский текст в латинский slug.
    
    Args:
        text: Строка для транслитерации
        
    Returns:
        Slug в нижнем регистре с дефисами вместо пробелов
    """
    if not text:
        return ''
    
    # Словарь транслитерации русских букв
    translit_map = {
        'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd',
        'е': 'e', 'ё': 'yo', 'ж': 'zh', 'з': 'z', 'и': 'i',
        'й': 'y', 'к': 'k', 'л': 'l', 'м': 'm', 'н': 'n',
        'о': 'o', 'п': 'p', 'р': 'r', 'с': 's', 'т': 't',
        'у': 'u', 'ф': 'f', 'х': 'h', 'ц': 'ts', 'ч': 'ch',
        'ш': 'sh', 'щ': 'sch', 'ъ': '', 'ы': 'y', 'ь': '',
        'э': 'e', 'ю': 'yu', 'я': 'ya',
        'А': 'A', 'Б': 'B', 'В': 'V', 'Г': 'G', 'Д': 'D',
        'Е': 'E', 'Ё': 'Yo', 'Ж': 'Zh', 'З': 'Z', 'И': 'I',
        'Й': 'Y', 'К': 'K', 'Л': 'L', 'М': 'M', 'Н': 'N',
        'О': 'O', 'П': 'P', 'Р': 'R', 'С': 'S', 'Т': 'T',
        'У': 'U', 'Ф': 'F', 'Х': 'H', 'Ц': 'Ts', 'Ч': 'Ch',
        'Ш': 'Sh', 'Щ': 'Sch', 'Ъ': '', 'Ы': 'Y', 'Ь': '',
        'Э': 'E', 'Ю': 'Yu', 'Я': 'Ya',
    }
    
    # Транслитерация
    slug = ''.join(translit_map.get(char, char) for char in text)
    
    # В нижний регистр
    slug = slug.lower()
    
    # Заменяем любые не буквенно-цифровые символы (кроме дефиса) на дефис
    slug = re.sub(r'[^a-z0-9-]', '-', slug)
    
    # Убираем множественные дефисы
    slug = re.sub(r'-+', '-', slug)
    
    # Убираем дефисы в начале и конце
    slug = slug.strip('-')
    
    return slug
